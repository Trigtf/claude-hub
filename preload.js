const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('hub', {
  homeDir: process.env.USERPROFILE || process.env.HOME || '.',
  pathsExist: (paths) => ipcRenderer.invoke('paths:exist', paths),
  claudeGet: () => ipcRenderer.invoke('claude:get'),
  claudeSet: (patch) => ipcRenderer.invoke('claude:set', patch),
  mcpList: (cwd) => ipcRenderer.invoke('mcp:list', cwd),
  mcpCheck: (cwd) => ipcRenderer.invoke('mcp:check', cwd),
  mcpAdd: (opts) => ipcRenderer.invoke('mcp:add', opts),
  mcpRemove: (opts) => ipcRenderer.invoke('mcp:remove', opts),
  getSettings: () => ipcRenderer.invoke('settings:get'),
  setSettings: (newProjectsPath, dryRun) => ipcRenderer.invoke('settings:set', newProjectsPath, dryRun),
  chooseFolder: (defaultPath) => ipcRenderer.invoke('dialog:folder', defaultPath),
  createProject: (name) => ipcRenderer.invoke('project:create', name),
  onNewFile: (cb) => ipcRenderer.on('files:new', (_e, info) => cb(info)),
  previewFile: (p) => ipcRenderer.invoke('file:preview', p),
  saveFile: (p) => ipcRenderer.invoke('file:save', p),
  openFile: (p) => ipcRenderer.invoke('file:open', p),
  revealFile: (p) => ipcRenderer.send('file:reveal', p),
  startDrag: (p) => ipcRenderer.send('file:drag', p),
  projectMenu: (projectPath, pinned) => ipcRenderer.send('project:menu', { path: projectPath, pinned }),
  onProjectAction: (cb) => ipcRenderer.on('project:action', (_e, msg) => cb(msg)),
  pinProject: (projectPath, name, pinned) => ipcRenderer.invoke('projects:pin', projectPath, name, pinned),
  setOrder: (paths) => ipcRenderer.invoke('projects:order', paths),
  listProjects: () => ipcRenderer.invoke('projects:list'),
  spawn: (opts) => ipcRenderer.invoke('pty:spawn', opts),
  write: (id, data) => ipcRenderer.send('pty:write', id, data),
  resize: (id, cols, rows) => ipcRenderer.send('pty:resize', id, cols, rows),
  kill: (id) => ipcRenderer.send('pty:kill', id),
  onData: (cb) => ipcRenderer.on('pty:data', (_e, id, data) => cb(id, data)),
  onExit: (cb) => ipcRenderer.on('pty:exit', (_e, id, code) => cb(id, code)),
  pathForFile: (file) => webUtils.getPathForFile(file),
  saveImage: (buffer, ext) => ipcRenderer.invoke('inbox:saveImage', buffer, ext),
  saveText: (text) => ipcRenderer.invoke('inbox:saveText', text),
  openInbox: () => ipcRenderer.invoke('inbox:open'),
  readClipboard: () => ipcRenderer.invoke('clipboard:read'),
  writeClipboard: (text) => ipcRenderer.send('clipboard:write', text),
});
